export function getCategoryDetails(predictedClass) {
  if (!predictedClass) return null;
  // Normalized lookup
  const clean = String(predictedClass).trim();
  if (TARGET_CATEGORIES[clean]) return TARGET_CATEGORIES[clean];

  for (const key of Object.keys(TARGET_CATEGORIES)) {
    if (clean.toLowerCase() === key.toLowerCase()) {
      return TARGET_CATEGORIES[key];
    }
  }

  // Fallback for partial matches
  if (/both|cas.*das/i.test(clean)) return TARGET_CATEGORIES['CAS & DAS'];
  if (/cas|wheeze|rhonch/i.test(clean)) return TARGET_CATEGORIES.CAS;
  if (/das|crackle|rale/i.test(clean)) return TARGET_CATEGORIES.DAS;
  if (/normal/i.test(clean)) return TARGET_CATEGORIES.Normal;

  return {
    code: clean,
    label: clean,
    shortDescription: 'Acoustic classification identified by CNN model.',
    clinicalSummary: `Acoustic category identified as ${clean}. Auscultation patterns evaluate airflow vibrations across time-frequency spectrogram domains.`,
    badgeClass: 'badge-cyan',
    themeColor: 'var(--accent-cyan)',
    soundType: 'Classified acoustic feature',
    duration: 'Evaluated window',
    frequencyRange: '50 Hz – 2000 Hz',
  };
}

